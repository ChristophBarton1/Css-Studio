import type { DesignSnapshot } from '../types';
import type { CornerStyle, ResolvedDesign, ShadowStyle } from './resolve-design';

export const ROLE_SELECTORS: Record<string, string> = {
  h1: 'h1',
  h2: 'h2',
  h3: 'h3',
  h4: 'h4',
  h5: 'h5',
  h6: 'h6',
  body: 'body',
  small: 'small, .text-muted',
  button: 'button, .btn, [role="button"]',
  link: 'a',
  code: 'code, pre',
};

const CORNER_FACTORS: Record<CornerStyle, number> = { sharp: 0, soft: 1, rounded: 1.8 };

const SHADOW_VALUES: Record<ShadowStyle, string> = {
  none: 'none',
  subtle: '0 1px 3px rgba(16, 24, 40, 0.08)',
  elevated: '0 8px 24px rgba(16, 24, 40, 0.14)',
};

function scaleRadius(base: string, corner: CornerStyle): string {
  const parsed = Number.parseFloat(base);
  if (Number.isNaN(parsed)) return base;
  const unit = base.replace(/^[\d.]+/, '') || 'px';
  return `${Math.round(parsed * CORNER_FACTORS[corner])}${unit}`;
}

/** Selectors touched by the current session, for `snapshot.changedSelectors`. */
export function changedSelectors(design: ResolvedDesign): string[] {
  const selectors = new Set<string>();
  for (const target of design.changedTargets) {
    const [kind, ...rest] = target.split(':');
    const name = rest.join(':');
    if (kind === 'color' || kind === 'global') selectors.add(':root');
    else if (kind === 'typography') selectors.add(ROLE_SELECTORS[name] ?? name);
    else if (kind === 'element') selectors.add(name);
  }
  return [...selectors];
}

/** Renders the working design as a standalone stylesheet. */
export function generateCss(design: ResolvedDesign, snapshot: DesignSnapshot): string {
  const lines: string[] = ['/* Generated by Style Studio */', ':root {'];
  for (const color of design.colors) {
    lines.push(`  --ss-color-${color.name}: ${color.value.toLowerCase()};`);
  }
  for (const [name, value] of Object.entries(snapshot.radii)) {
    lines.push(`  --ss-radius-${name}: ${scaleRadius(value, design.global.corner)};`);
  }
  lines.push(`  --ss-shadow: ${SHADOW_VALUES[design.global.shadow]};`);
  lines.push('}', '');

  for (const token of design.typography) {
    const selector = ROLE_SELECTORS[token.role] ?? token.role;
    lines.push(`${selector} {`);
    lines.push(`  font-family: ${token.fontFamily};`);
    lines.push(`  font-size: ${token.fontSize};`);
    lines.push(`  font-weight: ${token.fontWeight};`);
    lines.push(`  line-height: ${token.lineHeight};`);
    if (token.letterSpacing) lines.push(`  letter-spacing: ${token.letterSpacing};`);
    if (token.textTransform) lines.push(`  text-transform: ${token.textTransform};`);
    lines.push('}', '');
  }

  for (const [selector, props] of Object.entries(design.elements)) {
    lines.push(`${selector} {`);
    for (const [property, value] of Object.entries(props)) {
      lines.push(`  ${property}: ${value};`);
    }
    lines.push('}', '');
  }

  if (design.customCss.trim()) {
    lines.push('/* User-authored CSS */', design.customCss.trim(), '');
  }

  return lines.join('\n');
}
